const STORAGE_KEY = 'gihm_language';

export function getStoredLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  const stored = localStorage.getItem(STORAGE_KEY) as Language;
  return stored && translations[stored] ? stored : 'en';
}

export function t(key: string, lang?: Language): string {
  const l = lang ?? getStoredLanguage();
  return translations[l]?.[key] ?? translations.en[key] ?? key;
}

let currentLang: Language = getStoredLanguage();
let listeners: Array<() => void> = [];

export function setLanguage(lang: Language) {
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  listeners.forEach((fn) => fn());
}

export function getCurrentLanguage(): Language {
  return currentLang;
}

export function onLanguageChange(fn: () => void): () => void {
  listeners.push(fn);
  return () => { listeners = listeners.filter((f) => f !== fn); };
}

export function useTranslation() {
  const [lang, setLangState] = useState<Language>(currentLang);

  useEffect(() => {
    return onLanguageChange(() => setLangState(getCurrentLanguage()));
  }, []);

  const setLang = useCallback((l: Language) => {
    setLanguage(l);
  }, []);

  const translate = useCallback((key: string) => t(key, lang), [lang]);

  return { lang, setLang, t: translate };
}
