// Helper functions
export function searchDrugs(query: string): Drug[] {
  const q = query.toLowerCase();
  return DRUG_DATABASE.filter((d) =>
    d.genericName.toLowerCase().includes(q) ||
    d.brandName.toLowerCase().includes(q) ||
    d.category.toLowerCase().includes(q) ||
    d.id.toLowerCase().includes(q)
  );
}

export function getDrugsByCategory(category: string): Drug[] {
  return DRUG_DATABASE.filter((d) => d.category === category);
}

export function getControlledDrugs(): Drug[] {
  return DRUG_DATABASE.filter((d) => d.controlledStatus !== 'None');
}

export function getExpiringDrugs(withinDays: number = 90): Drug[] {
  const cutoff = new Date();
  cutoff.setDate(cutoff.getDate() + withinDays);
  return DRUG_DATABASE.filter((d) => new Date(d.expiryDate) <= cutoff);
}

export function getLowStockDrugs(): Drug[] {
  return DRUG_DATABASE.filter((d) => d.availableQuantity <= d.reorderLevel);
}

export function getDrugById(id: string): Drug | undefined {
  return DRUG_DATABASE.find((d) => d.id === id);
}

export function updateDrug(id: string, updates: Partial<Drug>): Drug | undefined {
  const index = DRUG_DATABASE.findIndex((d) => d.id === id);
  if (index === -1) return undefined;
  const merged: Drug = { ...DRUG_DATABASE[index], ...updates } as Drug;
  DRUG_DATABASE[index] = merged;
  return DRUG_DATABASE[index];
}
