export function districtType(name: string): "METROPOLITAN" | "MUNICIPAL" | "DISTRICT" {
  if (name.includes("Metropolitan")) return "METROPOLITAN";
  if (name.includes("Municipal")) return "MUNICIPAL";
  return "DISTRICT";
}

