type FacilityInput = Omit<SeedFacility, 'services' | 'departments'> & {
  services?: string[];
  departments?: string[];
};

/** Build a SeedFacility: catalog baseline + per-facility extras (deduped). */
function facility(f: FacilityInput): SeedFacility {
  return {
    ...f,
    services: [...new Set([...(SERVICES_BY_TYPE[f.type] ?? []), ...(f.services ?? [])])],
    departments: [...new Set([...(DEPARTMENTS_BY_TYPE[f.type] ?? []), ...(f.departments ?? [])])],
  };
}

